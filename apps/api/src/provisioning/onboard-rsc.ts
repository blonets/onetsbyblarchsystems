/**
 * Generates the per-token `onboard.rsc` RouterOS script.
 *
 * The tech pastes ONE line into the router terminal (per ARCHITECTURE §3.1):
 *
 *   /tool fetch mode=https address=<panel> src-path=/api/v1/onboard/<token>/onboard.rsc \
 *     dst-path=onboard.rsc; /import onboard.rsc
 *
 * The script then:
 *  1. creates the SSTP client (add takes only connect-to/user/password —
 *     live-validated on 6.49.17; the rest goes through /set),
 *  2. creates the least-privilege `panel-api` group + user,
 *  3. stamps identity (site slug) + panel-uuid into /system note,
 *  4. installs the watchdog scheduler (2 min),
 *  5. POSTs the callback to the platform.
 *
 * Pure function — fully unit-tested, no I/O.
 */

export interface OnboardScriptInput {
  /** Hub hostname/IP the SSTP client dials (port 443). */
  hubHost: string;
  sstpUsername: string;
  sstpPassword: string;
  /** Random password for the on-router `panel-api` user. */
  apiPassword: string;
  /** Platform UUID stamped as panel-uuid:<uuid> in /system note. */
  uuid: string;
  /** /system identity name (site slug, ≤64 chars). */
  siteSlug: string;
  /** Public panel host for the HTTPS callback, e.g. panel.example.com. */
  panelHost: string;
  /** Single-use onboarding token (auth for the .rsc fetch + callback). */
  token: string;
  /** Callback path, e.g. /api/v1/onboard/<token>/callback */
  callbackPath: string;
}

/** Escape a value for a double-quoted RouterOS string (also neutralizes `$`). */
export function rosEscape(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '$$');
}

export function buildOnboardScript(input: OnboardScriptInput): string {
  const hubHost = rosEscape(input.hubHost);
  const sstpUser = rosEscape(input.sstpUsername);
  const sstpPass = rosEscape(input.sstpPassword);
  const apiPass = rosEscape(input.apiPassword);
  const uuid = rosEscape(input.uuid);
  const siteSlug = rosEscape(input.siteSlug.slice(0, 64));
  const panelHost = rosEscape(input.panelHost);
  const callbackPath = rosEscape(input.callbackPath);

  const lines: string[] = [
    `# onboard.rsc — generated by the MikroTik fleet platform (single-use token).`,
    `# Safe to re-import: every step is guarded.`,
    ``,
    `:log info "panel-onboard: starting (uuid=${uuid})";`,
    ``,
    `# 1) SSTP client → hub (add takes only connect-to/user/password; rest via /set)`,
    `:if ([:len [/interface sstp-client find where comment="panel-sstp"]]=0) do={`,
    `  :local sstpId [/interface sstp-client add connect-to="${hubHost}" port=443 user="${sstpUser}" password="${sstpPass}" comment="panel-sstp"];`,
    `  /interface sstp-client set $sstpId profile=default-encryption authentication=mschap2 tls-version=only-1.2 verify-server-certificate=no disabled=no;`,
    `  :log info "panel-onboard: sstp client created";`,
    `} else={`,
    `  :log info "panel-onboard: sstp client already present";`,
    `}`,
    ``,
    `# 2) Least-privilege platform user (allow-list; no sensitive/sniff/reboot/policy)`,
    `:if ([:len [/user group find name=panel-api]]=0) do={`,
    `  /user group add name=panel-api policy=read,write,api,rest-api,test comment="platform management";`,
    `}`,
    `:if ([:len [/user find name=panel-api]]=0) do={`,
    `  /user add name=panel-api group=panel-api password="${apiPass}" comment="platform management";`,
    `} else={`,
    `  /user set panel-api password="${apiPass}" group=panel-api;`,
    `}`,
    ``,
    `# 3) Identity stamp (identity has no comment property — UUID goes in /system note)`,
    `/system identity set name="${siteSlug}";`,
    `/system note set note="panel-uuid=${uuid}";`,
    ``,
    `# 4) Watchdog: redial SSTP when the tunnel drops (every 2 min, from startup)`,
    `:if ([:len [/system scheduler find name=panel-watchdog]]=0) do={`,
    `  /system scheduler add name=panel-watchdog start-time=startup interval=2m on-event=":if ([:len [/interface sstp-client find where running and comment=\\"panel-sstp\\"]]=0) do={ /interface sstp-client disable [find where comment=\\"panel-sstp\\"]; :delay 2; /interface sstp-client enable [find where comment=\\"panel-sstp\\"]; /log warning \\"panel-watchdog: sstp redialed\\" }";`,
    `}`,
    ``,
    `# 5) Callback to the platform (HTTPS; token in path is the auth, single-use)`,
    `:local ver [/system resource get version];`,
    `:local board [/system resource get board-name];`,
    `:local payload ("{\\"uuid\\":\\"${uuid}\\",\\"version\\":\\"" . $ver . "\\",\\"board\\":\\"" . $board . \\"\\"}");`,
    `/tool fetch mode=https url="https://${panelHost}${callbackPath}" http-method=post http-data=$payload dst-path=panel-callback.txt check-certificate=no;`,
    `:log info "panel-onboard: callback sent";`,
    ``,
  ];
  return lines.join('\n');
}
