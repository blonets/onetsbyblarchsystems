/**
 * Generates the per-token `onboard.rsc` RouterOS script and periodic sync script.
 *
 * The tech pastes ONE line into the router terminal (per ARCHITECTURE §3.1):
 *
 *   { :local v [/system resource get version]; :local m [:pick $v 0 1];
 *     /tool fetch mode=https url=("https://<panel>/api/v1/onboard/<token>/onboard.rsc?v=" . $m)
 *     dst-path=onboard.rsc check-certificate=no; :delay 2s; /import onboard.rsc; }
 *
 * The script then:
 *  1. creates / updates the SSTP client,
 *  2. creates the least-privilege `panel-api` group + user (v7 gets rest-api policy, v6 safe),
 *  3. stamps identity (site slug) + panel-uuid into /system note,
 *  4. installs the watchdog scheduler (2 min auto-reconnect),
 *  5. installs linkscriptUpdate scheduler (12h auto-sync for new features/fixes),
 *  6. POSTs the callback to the platform,
 *  7. outputs visual confirmation banner in the terminal.
 *
 * Pure function — fully unit-tested, no I/O.
 */

export interface OnboardScriptInput {
  /** Hub hostname/IP the SSTP client dials (port 443). */
  hubHost: string;
  sstpUsername: string;
  sstpPassword: string;
  /** Random password for the on-router `panel-api` user. */
  apiPassword: string;
  /** Platform UUID stamped as panel-uuid:<uuid> in /system note. */
  uuid: string;
  /** /system identity name (site slug, ≤64 chars). */
  siteSlug: string;
  /** Public panel host for the HTTPS callback, e.g. panel.example.com. */
  panelHost: string;
  /** Single-use onboarding token (auth for the .rsc fetch + callback). */
  token: string;
  /** Callback path, e.g. /api/v1/onboard/<token>/callback */
  callbackPath: string;
  /** RouterOS major version hint: '6' | '7' | undefined */
  rosVersion?: string;
}

export interface SyncScriptInput {
  uuid: string;
  panelHost: string;
  hubHost: string;
  rosVersion?: string;
}

/** Escape a value for a double-quoted RouterOS string (also neutralizes `$`). */
export function rosEscape(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '$$');
}

export function buildOnboardScript(input: OnboardScriptInput): string {
  const hubHost = rosEscape(input.hubHost);
  const sstpUser = rosEscape(input.sstpUsername);
  const sstpPass = rosEscape(input.sstpPassword);
  const apiPass = rosEscape(input.apiPassword);
  const uuid = rosEscape(input.uuid);
  const siteSlug = rosEscape(input.siteSlug.slice(0, 64));
  const panelHost = rosEscape(input.panelHost);
  const callbackPath = rosEscape(input.callbackPath);
  const isV7 = input.rosVersion === '7';
  const groupPolicy = isV7
    ? 'read,write,api,test,password,sensitive,rest-api'
    : 'read,write,api,test,password,sensitive';

  const lines: string[] = [
    `# onboard.rsc — generated by the MikroTik fleet platform (single-use token).`,
    `# Safe to re-import: every step is guarded.`,
    ``,
    `:local ver [/system resource get version];`,
    `:log info "panel-onboard: starting (uuid=${uuid})";`,
    ``,
    `# 1) SSTP client → hub (add takes only connect-to/user/password; rest via /set)`,
    `:if ([:len [/interface sstp-client find where comment="panel-sstp"]]=0) do={`,
    `  /interface sstp-client add connect-to="${hubHost}" user="${sstpUser}" password="${sstpPass}" comment="panel-sstp";`,
    `  /interface sstp-client set [find where comment="panel-sstp"] profile=default-encryption authentication=mschap2 tls-version=only-1.2 verify-server-certificate=no disabled=no;`,
    `  :log info "panel-onboard: sstp client created";`,
    `} else={`,
    `  /interface sstp-client set [find where comment="panel-sstp"] connect-to="${hubHost}" user="${sstpUser}" password="${sstpPass}" profile=default-encryption authentication=mschap2 tls-version=only-1.2 verify-server-certificate=no disabled=no;`,
    `  :log info "panel-onboard: sstp client updated";`,
    `}`,
    ``,
    `# 2) Least-privilege platform user (allow-list; no sniff/reboot/policy)`,
    `:if ([:len [/user group find name=panel-api]]=0) do={`,
    `  /user group add name=panel-api policy=${groupPolicy} comment="platform management";`,
    `} else={`,
    `  /user group set [find name=panel-api] policy=${groupPolicy};`,
    `}`,
    `:if ([:len [/user find name=panel-api]]=0) do={`,
    `  /user add name=panel-api group=panel-api password="${apiPass}" comment="platform management";`,
    `} else={`,
    `  /user set [find name=panel-api] password="${apiPass}" group=panel-api;`,
    `}`,
    ``,
    `# 3) Identity stamp (identity has no comment property — UUID goes in /system note)`,
    `/system identity set name="${siteSlug}";`,
    `/system note set note="panel-uuid=${uuid}";`,
    ``,
    `# 4) Watchdog: redial SSTP when the tunnel drops (every 2 min, from startup)`,
    `:if ([:len [/system scheduler find name=panel-watchdog]]=0) do={`,
    `  /system scheduler add name=panel-watchdog start-time=startup interval=2m on-event=":if ([:len [/interface sstp-client find where running and comment=\\"panel-sstp\\"]]=0) do={ /interface sstp-client disable [find where comment=\\"panel-sstp\\"]; :delay 2; /interface sstp-client enable [find where comment=\\"panel-sstp\\"]; /log warning \\"panel-watchdog: sstp redialed\\" }";`,
    `} else={`,
    `  /system scheduler set [find name=panel-watchdog] interval=2m on-event=":if ([:len [/interface sstp-client find where running and comment=\\"panel-sstp\\"]]=0) do={ /interface sstp-client disable [find where comment=\\"panel-sstp\\"]; :delay 2; /interface sstp-client enable [find where comment=\\"panel-sstp\\"]; /log warning \\"panel-watchdog: sstp redialed\\" }";`,
    `}`,
    ``,
    `# 5) Periodic Sync / Auto-Update: linkscriptUpdate (every 12h, fetches latest script/features)`,
    `:if ([:len [/system scheduler find name=linkscriptUpdate]]=0) do={`,
    `  /system scheduler add name=linkscriptUpdate start-time=startup interval=12h on-event="{ :local v [/system resource get version]; :local m [:pick $v 0 1]; /tool fetch mode=https url=(\\"https://${panelHost}/api/v1/onboard/${uuid}/sync.rsc?v=\\" . $m) dst-path=panel-sync.rsc check-certificate=no; :delay 3s; /import panel-sync.rsc; /log info \\"linkscriptUpdate: synced\\"; }";`,
    `} else={`,
    `  /system scheduler set [find name=linkscriptUpdate] interval=12h on-event="{ :local v [/system resource get version]; :local m [:pick $v 0 1]; /tool fetch mode=https url=(\\"https://${panelHost}/api/v1/onboard/${uuid}/sync.rsc?v=\\" . $m) dst-path=panel-sync.rsc check-certificate=no; :delay 3s; /import panel-sync.rsc; /log info \\"linkscriptUpdate: synced\\"; }";`,
    `}`,
    ``,
    `# 6) Callback to the platform (HTTPS; token in path is the auth, single-use)`,
    `:local board [/system resource get board-name];`,
    `:local payload ("{\\"uuid\\":\\"${uuid}\\",\\"version\\":\\"" . $ver . "\\",\\"board\\":\\"" . $board . "\\"}");`,
    `:delay 3s;`,
    `:local callbackUrl ("https://${panelHost}${callbackPath}?uuid=${uuid}&version=" . $ver . "&board=" . $board);`,
    `/tool fetch mode=https url=$callbackUrl http-method=post http-data=$payload dst-path=panel-callback.txt check-certificate=no;`,
    `:log info "panel-onboard: callback sent";`,
    ``,
    `# 7) Terminal Confirmation Banner`,
    `:put "=================================================";`,
    `:put "  [+] ONETS BY BLARCH - Router Connected";`,
    `:put ("  [+] UUID: ${uuid}");`,
    `:put ("  [+] Version: " . $ver);`,
    `:put "  [+] Watchdog: Active (2m auto-reconnect)";`,
    `:put "  [+] Auto-Update: Active (12h linkscriptUpdate)";`,
    `:put "=================================================";`,
  ];
  return lines.join('\n');
}

export function buildSyncScript(input: SyncScriptInput): string {
  const uuid = rosEscape(input.uuid);
  const panelHost = rosEscape(input.panelHost);
  const hubHost = rosEscape(input.hubHost);

  const lines: string[] = [
    `# panel-sync.rsc — periodic sync & health check (${uuid})`,
    `:log info "panel-sync: starting periodic sync";`,
    ``,
    `# 1) Ensure watchdog is present and configured`,
    `:if ([:len [/system scheduler find name=panel-watchdog]]=0) do={`,
    `  /system scheduler add name=panel-watchdog start-time=startup interval=2m on-event=":if ([:len [/interface sstp-client find where running and comment=\\"panel-sstp\\"]]=0) do={ /interface sstp-client disable [find where comment=\\"panel-sstp\\"]; :delay 2; /interface sstp-client enable [find where comment=\\"panel-sstp\\"]; /log warning \\"panel-watchdog: sstp redialed\\" }";`,
    `} else={`,
    `  /system scheduler set [find name=panel-watchdog] interval=2m on-event=":if ([:len [/interface sstp-client find where running and comment=\\"panel-sstp\\"]]=0) do={ /interface sstp-client disable [find where comment=\\"panel-sstp\\"]; :delay 2; /interface sstp-client enable [find where comment=\\"panel-sstp\\"]; /log warning \\"panel-watchdog: sstp redialed\\" }";`,
    `}`,
    ``,
    `# 2) Ensure linkscriptUpdate is present (12h)`,
    `:if ([:len [/system scheduler find name=linkscriptUpdate]]=0) do={`,
    `  /system scheduler add name=linkscriptUpdate start-time=startup interval=12h on-event="{ :local v [/system resource get version]; :local m [:pick $v 0 1]; /tool fetch mode=https url=(\\"https://${panelHost}/api/v1/onboard/${uuid}/sync.rsc?v=\\" . $m) dst-path=panel-sync.rsc check-certificate=no; :delay 3s; /import panel-sync.rsc; /log info \\"linkscriptUpdate: synced\\"; }";`,
    `}`,
    ``,
    `# 3) Check SSTP connection and redial if disconnected`,
    `:if ([:len [/interface sstp-client find where running and comment="panel-sstp"]]=0) do={`,
    `  /interface sstp-client disable [find where comment="panel-sstp"];`,
    `  :delay 2;`,
    `  /interface sstp-client enable [find where comment="panel-sstp"];`,
    `  :log warning "panel-sync: redialed dropped sstp";`,
    `}`,
    ``,
    `:log info "panel-sync: sync complete";`,
  ];
  return lines.join('\n');
}
