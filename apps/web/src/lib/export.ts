'use client';

/** Download a text file from the browser (no server round-trip). */
export function downloadTextFile(filename: string, content: string, mime = 'text/plain;charset=utf-8'): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}

function csvCell(v: string | number | null | undefined): string {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** rows[0] = header. Prepends a BOM so Excel opens Arabic correctly. */
export function downloadCsv(filename: string, rows: Array<Array<string | number | null | undefined>>): void {
  const body = rows.map((r) => r.map(csvCell).join(',')).join('\r\n');
  downloadTextFile(filename, '﻿' + body, 'text/csv;charset=utf-8');
}

/** Escape a value for a RouterOS double-quoted script string. */
export function rosEscape(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

export interface VoucherExportRow {
  name: string;
  password: string;
  profile?: string | null;
  comment?: string | null;
  disabled?: boolean;
}

/** `/ip hotspot user add …` lines, importable via `/import` on the router. */
export function buildHotspotUsersRsc(rows: VoucherExportRow[]): string {
  const lines = [
    '# Generated by MikroTik Fleet panel — import with: /import file-name=vouchers.rsc',
    `# ${new Date().toISOString()}`,
    '',
  ];
  for (const r of rows) {
    const parts = [
      '/ip hotspot user add',
      `name="${rosEscape(r.name)}"`,
      `password="${rosEscape(r.password)}"`,
    ];
    if (r.profile) parts.push(`profile="${rosEscape(r.profile)}"`);
    if (r.comment) parts.push(`comment="${rosEscape(r.comment)}"`);
    parts.push(`disabled=${r.disabled ? 'yes' : 'no'}`);
    lines.push(parts.join(' '));
  }
  lines.push('');
  return lines.join('\n');
}

export function downloadHotspotUsersRsc(filename: string, rows: VoucherExportRow[]): void {
  downloadTextFile(filename, buildHotspotUsersRsc(rows));
}
